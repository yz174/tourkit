/**
 * Bundle skills/tourkit/scripts/recorder-browser.js from build/recorder-entry.js.
 *
 * The bundle is committed on purpose. The skill installs standalone, outside this repo,
 * where @tourkit/core is not on disk; the recorder still has to run. Committing it means
 * the two copies of the element-description logic can drift, so recorder-bundle.test.ts
 * fails the build if the committed file stops matching its source.
 *
 * Usage:
 *   node skills/tourkit/build/build-recorder.mjs          write the bundle
 *   node skills/tourkit/build/build-recorder.mjs --check  report whether it is stale
 */

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

export const ENTRY = path.join(__dirname, "recorder-entry.js");
export const OUTPUT = path.join(__dirname, "..", "scripts", "recorder-browser.js");

// The two suppressions below must be the first comment in the generated file: biome lints
// committed files, and reformatting bundler output would fight this script on every build.
const HEADER = `// biome-ignore-all lint: generated bundle
// biome-ignore-all format: generated bundle
/**
 * @generated by skills/tourkit/build/build-recorder.mjs — DO NOT EDIT.
 *
 * Source: skills/tourkit/build/recorder-entry.js
 * Bundled from @tourkit/core/dom so the recorder and the player agree on what a target is.
 * Rebuild: node skills/tourkit/build/build-recorder.mjs
 */
`;

/**
 * Returns the bundle text. Wrapped in an IIFE so a plain `<script src>` works everywhere,
 * including an Electron or Tauri webview that will not take a module MIME type.
 */
export function buildRecorder() {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "tourkit-recorder-"));
  const out = path.join(temp, "bundle.js");
  try {
    // bun.exe by name rather than through a shell: shell:true would concatenate the
    // temp path unescaped, and the deprecation warning it triggers pollutes stderr.
    const bun = process.platform === "win32" ? "bun.exe" : "bun";
    const result = spawnSync(
      bun,
      ["build", ENTRY, "--target=browser", "--format=esm", `--outfile=${out}`],
      { encoding: "utf-8" },
    );
    if (result.error) {
      throw new Error(`could not run ${bun}: ${result.error.message}`);
    }
    if (result.status !== 0) {
      throw new Error(`bun build failed:\n${result.stderr || result.stdout}`);
    }
    const bundled = fs.readFileSync(out, "utf-8").replace(/\r\n/g, "\n").trimEnd();
    return `${HEADER}(() => {\n${bundled}\n})();\n`;
  } finally {
    try {
      fs.rmSync(temp, { recursive: true, force: true });
    } catch {}
  }
}

/** Line endings are normalized on both sides: git's autocrlf must not decide freshness. */
export function readCommitted() {
  try {
    return fs.readFileSync(OUTPUT, "utf-8").replace(/\r\n/g, "\n");
  } catch {
    return null;
  }
}

function main() {
  const check = process.argv.includes("--check");
  const built = buildRecorder();
  const committed = readCommitted();

  if (check) {
    const fresh = committed === built;
    console.log(
      JSON.stringify({
        ok: fresh,
        file: path.relative(process.cwd(), OUTPUT).split(path.sep).join("/"),
        fresh,
        ...(fresh
          ? {}
          : {
              message:
                "committed bundle is stale. Run: node skills/tourkit/build/build-recorder.mjs",
            }),
      }),
    );
    process.exit(fresh ? 0 : 1);
  }

  fs.writeFileSync(OUTPUT, built, "utf-8");
  console.log(
    JSON.stringify({
      ok: true,
      wrote: path.relative(process.cwd(), OUTPUT).split(path.sep).join("/"),
      bytes: Buffer.byteLength(built),
      changed: committed !== built,
    }),
  );
}

if (process.argv[1]?.endsWith("build-recorder.mjs")) main();
